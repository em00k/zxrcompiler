//! Emits a grammar's tables as Rust source, for a build script to write into
//! `OUT_DIR` and the crate to `include!`.

use crate::build::Tables;
use crate::grammar::Grammar;
use crate::runtime::NO_ACTION;
use std::fmt::Write;

fn constant_name(name: &str) -> String {
    match name {
        "$end" => "END_OF_INPUT".into(),
        "error" => "ERROR_TOKEN".into(),
        other => other.to_uppercase(),
    }
}

/// Generates the module body: terminal ids, the `Rule` enum naming every
/// action, and a `TABLES` constant.
pub fn generate(grammar: &Grammar, tables: &Tables) -> String {
    generate_with(grammar, tables, None)
}

/// Like [`generate`], but without a `Rule` enum of its own: the rules are
/// those of another grammar's module, named by `rule_path`. For a grammar
/// that is a subset of another and shares its actions.
pub fn generate_sharing_rules(grammar: &Grammar, tables: &Tables, rule_path: &str) -> String {
    generate_with(grammar, tables, Some(rule_path))
}

fn generate_with(grammar: &Grammar, tables: &Tables, rule_path: Option<&str>) -> String {
    let nt = grammar.terminals.len();
    let nn = grammar.nonterminals.len();
    let mut out = String::from("// Generated by zxr-lalr from the grammar file. Do not edit.\n\n");

    out.push_str("#[allow(dead_code)]\npub mod term {\n");
    for (i, name) in grammar.terminals.iter().enumerate() {
        writeln!(out, "    pub const {}: u16 = {i};", constant_name(name)).unwrap();
    }
    out.push_str("}\n\n");

    match rule_path {
        Some(path) => writeln!(out, "use {path}::Rule;\n").unwrap(),
        None => {
            out.push_str("/// The action of each production, named after the grammar's `@` lines.\n");
            out.push_str("#[allow(non_camel_case_types, dead_code)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\npub enum Rule {\n    start_,\n");
            for action in &grammar.actions {
                writeln!(out, "    {action},").unwrap();
            }
            out.push_str("}\n\n");
        }
    }

    writeln!(out, "pub static RULES: [Rule; {}] = [", grammar.rules.len()).unwrap();
    for rule in &grammar.rules {
        let name = if rule.number == 0 { "start_" } else { &rule.action };
        writeln!(out, "    Rule::{name},").unwrap();
    }
    out.push_str("];\n\n");

    writeln!(out, "static PRODUCTIONS: [zxr_lalr::Production; {}] = [", grammar.rules.len()).unwrap();
    for rule in &grammar.rules {
        writeln!(out, "    zxr_lalr::Production {{ lhs: {}, len: {} }},", rule.lhs - nt, rule.rhs.len()).unwrap();
    }
    out.push_str("];\n\n");

    let states = tables.action.len();
    writeln!(out, "static ACTION: [i32; {}] = [", states * nt).unwrap();
    for row in &tables.action {
        let cells: Vec<String> = (0..nt).map(|t| row.get(&t).copied().flatten().unwrap_or(NO_ACTION).to_string()).collect();
        writeln!(out, "    {},", cells.join(", ")).unwrap();
    }
    out.push_str("];\n\n");

    writeln!(out, "static GOTO: [i32; {}] = [", states * nn).unwrap();
    for row in &tables.goto {
        let cells: Vec<String> = (0..nn).map(|n| row.get(&(n + nt)).map_or(-1, |&t| t as i32).to_string()).collect();
        writeln!(out, "    {},", cells.join(", ")).unwrap();
    }
    out.push_str("];\n\n");

    writeln!(out, "static TERMINAL_NAMES: [&str; {nt}] = [").unwrap();
    for name in &grammar.terminals {
        writeln!(out, "    {name:?},").unwrap();
    }
    out.push_str("];\n\n");

    writeln!(
        out,
        "pub static TABLES: zxr_lalr::Tables = zxr_lalr::Tables {{\n    n_terminals: {nt},\n    n_nonterminals: {nn},\n    action: &ACTION,\n    goto: &GOTO,\n    productions: &PRODUCTIONS,\n    terminal_names: &TERMINAL_NAMES,\n    end: {},\n    error: {},\n}};",
        grammar.end(),
        grammar.terminal("error").unwrap()
    )
    .unwrap();
    out
}
