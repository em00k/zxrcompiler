//! A lexer driver that matches the way PLY's `lex` does.
//!
//! A lexer is described by a `.lex` file: for each state, the rules in the
//! order they are tried. At each position the first rule whose expression
//! matches wins, whatever its length. What a rule then does (change state,
//! rewrite the token, drop it) is ordinary Rust in the lexer that owns the
//! driver, dispatched on the rule's function name.
//!
//! ```text
//! # state <TAB> function <TAB> token type <TAB> regular expression
//! INITIAL	t_INITIAL_ID	ID	[_a-zA-Z][_a-zA-Z0-9]*
//! INITIAL	t_error	error	-
//! INITIAL	-	ignore	' \t'
//! ```

use std::cell::RefCell;
use std::rc::Rc;
use zxr_re::{Flags, Match, Regex};

pub struct Rule {
    /// Index into [`Spec::functions`].
    pub function: u16,
    /// Index into [`Spec::tokens`]: the type a token gets unless the action changes it.
    pub token: u16,
    pub regex: Regex,
}

pub struct State {
    pub name: String,
    pub rules: Vec<Rule>,
    /// Whether the state has an error function. PLY raises if it has none,
    /// and also if it has one that does not skip anything.
    pub has_error_function: bool,
    pub ignore: Vec<char>,
}

pub struct Spec {
    pub states: Vec<State>,
    pub functions: Vec<String>,
    pub tokens: Vec<String>,
}

impl Spec {
    /// Parses a `.lex` file. `functions` fixes the numbering of rule
    /// functions, so that it can agree with a generated enum.
    pub fn parse(text: &str, functions: &[&str]) -> Result<Spec, String> {
        let mut spec = Spec { states: Vec::new(), functions: functions.iter().map(|f| f.to_string()).collect(), tokens: Vec::new() };
        for (index, line) in text.lines().enumerate() {
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let at = |msg: String| format!("line {}: {msg}", index + 1);
            let fields: Vec<&str> = line.splitn(4, '\t').collect();
            let [state, function, token, regex] = fields[..] else { return Err(at("expected four tab-separated fields".into())) };
            let state_index = match spec.states.iter().position(|s| s.name == state) {
                Some(i) => i,
                None => {
                    spec.states.push(State { name: state.to_string(), rules: Vec::new(), has_error_function: false, ignore: Vec::new() });
                    spec.states.len() - 1
                }
            };
            match token {
                "error" if regex == "-" => spec.states[state_index].has_error_function = function != "-",
                "ignore" if function == "-" => {
                    let inner = regex.trim_matches('\'');
                    spec.states[state_index].ignore = inner.replace("\\t", "\t").chars().collect();
                }
                _ => {
                    let function = functions.iter().position(|f| *f == function).ok_or_else(|| at(format!("unknown function {function}")))? as u16;
                    let token = match spec.tokens.iter().position(|t| t == token) {
                        Some(i) => i,
                        None => {
                            spec.tokens.push(token.to_string());
                            spec.tokens.len() - 1
                        }
                    } as u16;
                    let regex = Regex::new(regex, Flags::VERBOSE).map_err(|e| at(e.to_string()))?;
                    spec.states[state_index].rules.push(Rule { function, token, regex });
                }
            }
        }
        Ok(spec)
    }

    pub fn state(&self, name: &str) -> usize {
        self.states.iter().position(|s| s.name == name).unwrap_or_else(|| panic!("no lexer state {name}"))
    }
}

/// The function names used in a `.lex` file, in order of first appearance.
/// A build script turns these into an enum.
pub fn function_names(text: &str) -> Vec<String> {
    let mut names: Vec<String> = Vec::new();
    for line in text.lines().filter(|l| !l.is_empty() && !l.starts_with('#')) {
        let fields: Vec<&str> = line.splitn(4, '\t').collect();
        if fields.len() == 4 && fields[1] != "-" && fields[2] != "error" && !names.iter().any(|n| n == fields[1]) {
            names.push(fields[1].to_string());
        }
    }
    names
}

/// Rust source for an enum of a `.lex` file's rule functions.
pub fn generate(text: &str) -> String {
    let names = function_names(text);
    let mut out = String::from("// Generated by zxr-lex from the .lex file. Do not edit.\n\n");
    out.push_str("#[allow(non_camel_case_types, dead_code)]\n#[derive(Clone, Copy, Debug, PartialEq, Eq)]\n#[repr(u16)]\npub enum Func {\n");
    for name in &names {
        out.push_str(&format!("    {name},\n"));
    }
    out.push_str("}\n\n");
    out.push_str(&format!("pub static FUNCTIONS: [&str; {}] = [\n", names.len()));
    for name in &names {
        out.push_str(&format!("    {name:?},\n"));
    }
    out.push_str("];\n\n");
    out.push_str(&format!("pub static FUNCS: [Func; {}] = [\n", names.len()));
    for name in &names {
        out.push_str(&format!("    Func::{name},\n"));
    }
    out.push_str("];\n");
    out
}

pub enum Step {
    /// A rule matched; the position is already past the match.
    Rule { function: u16, token: u16, found: Match },
    /// No rule matches at this position.
    NoMatch { pos: usize },
    End,
}

/// One PLY `Lexer` object: input, position, line number and state.
#[derive(Clone)]
pub struct Lexer {
    spec: Rc<Spec>,
    pub data: Rc<Vec<char>>,
    pub pos: usize,
    pub lineno: u32,
    state: usize,
    /// PLY's `clone()` is a shallow copy, so a clone shares the state stack
    /// of the lexer it was made from.
    stack: Rc<RefCell<Vec<usize>>>,
}

impl Lexer {
    pub fn new(spec: Rc<Spec>) -> Lexer {
        let initial = spec.state("INITIAL");
        Lexer { spec, data: Rc::new(Vec::new()), pos: 0, lineno: 1, state: initial, stack: Rc::new(RefCell::new(Vec::new())) }
    }

    pub fn spec(&self) -> &Rc<Spec> {
        &self.spec
    }

    pub fn input(&mut self, data: Rc<Vec<char>>) {
        self.data = data;
        self.pos = 0;
    }

    pub fn state_name(&self) -> &str {
        &self.spec.states[self.state].name
    }

    pub fn begin(&mut self, state: &str) {
        self.state = self.spec.state(state);
    }

    pub fn push_state(&mut self, state: &str) {
        self.stack.borrow_mut().push(self.state);
        self.begin(state);
    }

    pub fn pop_state(&mut self) {
        self.state = self.stack.borrow_mut().pop().expect("pop_state on an empty lexer state stack");
    }

    /// The text of a match.
    pub fn text(&self, found: &Match) -> String {
        self.data[found.start..found.end].iter().collect()
    }

    pub fn step(&mut self) -> Step {
        let data = Rc::clone(&self.data);
        while self.pos < data.len() {
            let state = &self.spec.states[self.state];
            if state.ignore.contains(&data[self.pos]) {
                self.pos += 1;
                continue;
            }
            for rule in &state.rules {
                if let Some(found) = rule.regex.match_at(&data, self.pos) {
                    self.pos = found.end;
                    return Step::Rule { function: rule.function, token: rule.token, found };
                }
            }
            return Step::NoMatch { pos: self.pos };
        }
        // PLY leaves the position one past the end once the input is used up.
        self.pos = data.len() + 1;
        Step::End
    }
}
